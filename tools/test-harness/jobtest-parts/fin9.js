// Finance, second round: variation into an application, PDF BOQ import, plots, pay run, price book, cost codes, Team, VAT rates.
const path = require('path'), fs = require('fs');
const NEAR = (a, b) => Math.abs(Number(a) - b) < 0.005;
const {PDFDocument, StandardFonts} = require(path.join(__dirname, '../../../app-native/node_modules/pdf-lib'));
