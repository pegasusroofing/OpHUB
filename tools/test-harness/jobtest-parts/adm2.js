// Company admin, for real: add, edit and delete on rows this test makes. Anything the guard holds is reported, not forced.
const path = require('path'), fs = require('fs');
module.exports = async ({as, step, state, keep, samples, OUT}) => {
  const a = await as('admin');
  const say = async (n = 400) => (await a.text()).replace(/\s+/g, ' ').slice(0, n);
  const pdf = path.join(samples, 'sample.pdf');
  const prompt = async (val) => { const el = a.page.locator('input').locator('visible=true').last(); await el.fill(val); await a.page.waitForTimeout(200); await a.page.getByText('OK', {exact: true}).locator('visible=true').last().click({timeout: 7000}); await a.page.waitForTimeout(2500); };
  const q = (s) => encodeURIComponent(s);
  const blur = async () => { await a.page.keyboard.press('Tab'); await a.page.waitForTimeout(1800); };

  await step('Suppliers: add, edit email, delete', async () => {
    await a.go('/pm/admin/suppliers', 4000);
    await a.tap('+ Add Supplier', {wait: 700});
    await a.fill('Supplier name', 'ZZ Adm Supplier');
    await a.fill('Supplier order email', 'zz-adm@example.invalid');
    await a.tap('Add Supplier', {wait: 3000});
    const r1 = (await a.get(`suppliers?select=id,email&name=eq.${q('ZZ Adm Supplier')}`))[0];
    if (!r1) return {ok: false, note: await say(300)};
    await a.tap('ZZ Adm Supplier', {wait: 900});
    await a.shot('sup-open');
    const em = a.page.getByText('Order email', {exact: true}).locator('visible=true').last().locator('xpath=following::input[1]');
    await em.fill('zz-adm2@example.invalid'); await blur();
    const r2 = (await a.get(`suppliers?select=email&id=eq.${r1.id}`))[0];
    await a.tap('Delete supplier', {wait: 1000});
    await a.shot('sup-del');
    await a.page.getByText(/^(Delete|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`suppliers?select=id&id=eq.${r1.id}`))[0];
    return {ok: !!r1 && r2.email === 'zz-adm2@example.invalid' && !r3, note: `edit ${r2.email}, ${r3 ? 'still there (guard hold?)' : 'deleted'}`};
  });
  await step('HAVS tools: add, edit magnitude, delete', async () => {
    await a.go('/pm/admin/havstools', 4000);
    await a.tap('+ Add Tool', {wait: 700});
    await a.fill('Tool name', 'ZZ Adm Grinder');
    await a.fill('Vibration magnitude (m/s²)', '4');
    await a.tap('Add Tool', {wait: 3000});
    const r1 = (await a.get(`havs_tools?select=id,name,vibration_magnitude&name=ilike.${q('zz adm grinder')}`))[0];
    if (!r1) return {ok: false, note: await say(300)};
    const row = a.page.locator(`input`).locator('visible=true');
    const n = await row.count();
    let edited = null;
    for (let i = 0; i < n; i++) if (/grinder/i.test(await row.nth(i).inputValue())) { const m = row.nth(i + 1); await m.fill('6'); await blur(); edited = (await a.get(`havs_tools?select=vibration_magnitude&id=eq.${r1.id}`))[0]; break; }
    await a.shot('havs');
    await a.page.getByText('🗑').locator('visible=true').last().click();
    await a.page.waitForTimeout(1000);
    await a.page.getByText(/^(Delete|Remove|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`havs_tools?select=id&id=eq.${r1.id}`))[0];
    return {ok: Number(edited?.vibration_magnitude) === 6 && !r3, note: `mag ${edited?.vibration_magnitude}, ${r3 ? 'still there' : 'deleted'}`};
  });
  await step('Rate card: add item 12.50, delete', async () => {
    await a.go('/pm/admin/ratecard', 4000);
    await a.tap('+ Add Rate Item', {wait: 700});
    await a.fill('Category, e.g. Pitched Roofing', 'ZZ Roofing');
    await a.fill('Item name, e.g. Strip', 'ZZ Strip');
    await a.fill('Rate (£) e.g. 12.50', '12.50');
    await a.shot('rate-add');
    await a.tap('Add Item', {wait: 3000});
    const r1 = (await a.get(`price_rate_items?select=id,rate&name=eq.${q('ZZ Strip')}`))[0];
    if (!r1) return {ok: false, note: await say(300)};
    await a.shot('rate-list');
    await a.page.getByText('🗑').locator('visible=true').last().click();
    await a.page.waitForTimeout(1000);
    await a.page.getByText(/^(Remove|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`price_rate_items?select=id&id=eq.${r1.id}`))[0];
    return {ok: Number(r1.rate) === 12.5 && !r3, note: `rate ${r1.rate}, ${r3 ? 'still there' : 'deleted'}`};
  });
  await step('SoW library: template, section, task, delete', async () => {
    await a.go('/pm/admin/sowlibrary', 4000);
    await a.tap('+ New Template', {wait: 900});
    await prompt('ZZ Adm Template');
    await a.shot('sow-new');
    const r1 = (await a.get(`sow_library_templates?select=id&name=eq.${q('ZZ Adm Template')}`))[0];
    if (!r1) return {ok: false, note: await say(300)};
    const add = async (ph, v) => { const el = a.page.locator(`input[placeholder="${ph}"]`).locator('visible=true').last(); await el.fill(v); await el.locator('xpath=following-sibling::*[1]').click(); await a.page.waitForTimeout(2500); };
    await add('Add a section', 'ZZ Section');
    await add('Add a task to this section', 'ZZ Task');
    await a.shot('sow-built');
    const s = await a.get(`sow_library_sections?select=id&template_id=eq.${r1.id}`), t = await a.get(`sow_library_tasks?select=id&template_id=eq.${r1.id}`);
    await a.tap('🗑 Delete Template', {wait: 1000});
    await a.page.getByText(/^(Delete|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`sow_library_templates?select=id&id=eq.${r1.id}`))[0];
    return {ok: s.length === 1 && t.length === 1 && !r3, note: `sections ${s.length}, tasks ${t.length}, ${r3 ? 'still there' : 'deleted'}`};
  });
  await step('TBT templates: add a PDF to the bank, opens listed, delete', async () => {
    await a.go('/pm/admin/tbt', 4000);
    await a.fill('Title, e.g. Alcohol & Drugs', 'ZZ Adm Talk');
    await a.pick(() => a.tap('Choose PDF', {wait: 0}), [pdf], 1000);
    await a.tap('Add to Bank', {wait: 4000});
    await a.shot('tbt');
    const r1 = (await a.get(`tbt_templates?select=id,title,storage_path&title=eq.${q('ZZ Adm Talk')}`))[0];
    if (!r1) return {ok: false, note: await say(300)};
    await a.page.getByText('🗑').locator('visible=true').last().click();
    await a.page.waitForTimeout(1000);
    await a.page.getByText(/^(Remove|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`tbt_templates?select=id&id=eq.${r1.id}`))[0];
    return {ok: !!r1.storage_path && !r3, note: `file stored, ${r3 ? 'still there' : 'deleted'}`};
  });
  await step('RAMS library: new hazard, title and harm saved, delete', async () => {
    await a.go('/pm/admin/ramslibrary', 4000);
    await a.tap('+ New hazard', {wait: 2500});
    await a.shot('rams-edit');
    const inp = a.page.locator('input, textarea').locator('visible=true');
    const n = await inp.count();
    let done = false;
    for (let i = 0; i < n; i++) { if ((await inp.nth(i).inputValue()) === 'New hazard') { await inp.nth(i).fill('ZZ Adm Hazard'); done = true; break; } }
    await a.tap('Save', {wait: 3000});
    const r1 = (await a.get(`rams_library_items?select=id,title,data&title=eq.${q('ZZ Adm Hazard')}`))[0];
    if (!r1) return {ok: false, note: `typed ${done}: ` + await say(300)};
    await a.fill('Search…', 'ZZ Adm');
    await a.page.waitForTimeout(600);
    await a.page.getByText('⋯').locator('visible=true').last().click();
    await a.page.waitForTimeout(800);
    await a.tap('🗑 Delete', {wait: 900});
    await a.page.getByText(/^(Delete|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`rams_library_items?select=id&id=eq.${r1.id}`))[0];
    return {ok: !r3, note: r3 ? 'still there' : 'added, saved, deleted'};
  });
  await step('COSHH library: folder, product, delete product', async () => {
    await a.go('/pm/admin/coshh', 4000);
    await a.tap('+ Folder', {wait: 900});
    await prompt('ZZ Adm Folder');
    const f = (await a.get(`coshh_library_folders?select=id&name=eq.${q('ZZ Adm Folder')}`))[0];
    await a.shot('coshh-folder');
    await a.tap('Products (data sheets)', {wait: 1500});
    await a.tap('+ Add a product', {wait: 900});
    await prompt('ZZ Adm Product');
    await a.page.waitForTimeout(1500);
    await a.shot('coshh-prod');
    const pid = (a.page.url().match(/coshh\/([0-9a-f-]{36})/) || [])[1];
    return {ok: !!f && !!pid, note: `folder ${f ? 'saved' : 'NOT'}; product ${pid ? 'opened' : 'NOT: ' + await say(200)}; ${(await say(400)).slice(40, 300)}`};
  });
  await step('Report templates: new, rename, delete', async () => {
    await a.go('/pm/admin/templates', 4000);
    await a.tap('+ New Template', {wait: 3500});
    await a.shot('tpl-edit');
    const id = (a.page.url().match(/templates\/([0-9a-f-]{36})/) || [])[1];
    if (!id) return {ok: false, note: await say(300)};
    const nm = a.page.locator('input').locator('visible=true').first();
    await nm.fill('ZZ Adm Report');
    await a.page.waitForTimeout(400);
    await a.page.getByText(/^Save/).locator('visible=true').last().click();
    await a.page.waitForTimeout(3000);
    const r1 = (await a.get(`report_templates?select=name&id=eq.${id}`))[0];
    await a.go('/pm/admin/templates', 4000);
    await a.tap(r1.name, {wait: 700}).catch(() => {});
    const row = a.page.getByText(r1.name, {exact: true}).locator('visible=true').first();
    await row.locator('xpath=following::*[text()="⋮"][1]').click();
    await a.page.waitForTimeout(800);
    await a.tap('🗑 Delete', {wait: 900});
    await a.page.getByText(/^(Delete|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`report_templates?select=id&id=eq.${id}`))[0];
    return {ok: r1.name === 'ZZ Adm Report' && !r3, note: `${r1.name}, ${r3 ? 'still there' : 'deleted'}`};
  });
  await step('Signing template: upload sample, boxes screen, delete', async () => {
    await a.go('/pm/admin/signtemplates', 4000);
    await a.fill('Template name, e.g. Hyde RAMS form', 'ZZ Adm Sign');
    await a.pick(() => a.tap('Choose sample PDF', {wait: 0}), [pdf], 1000);
    await a.tap('Upload & set boxes', {wait: 6000});
    await a.shot('sign-boxes');
    const r1 = (await a.get(`sign_layout_templates?select=id,name,storage_path&name=eq.${q('ZZ Adm Sign')}`))[0];
    if (!r1) return {ok: false, note: await say(300)};
    await a.go('/pm/admin/signtemplates', 4000);
    await a.page.getByText('ZZ Adm Sign').locator('visible=true').first().locator('xpath=following::*[text()="⋯"][1]').click().catch(async () => { await a.page.getByText('ZZ Adm Sign').locator('visible=true').first().click(); });
    await a.page.waitForTimeout(900);
    await a.shot('sign-menu');
    await a.page.getByText(/Delete/).locator('visible=true').last().click();
    await a.page.waitForTimeout(900);
    await a.page.getByText(/^(Delete|Yes)$/).locator('visible=true').last().click();
    await a.page.waitForTimeout(2500);
    const r3 = (await a.get(`sign_layout_templates?select=id&id=eq.${r1.id}`))[0];
    return {ok: !!r1.storage_path && !r3, note: `${r3 ? 'still there' : 'deleted'}`};
  });
};
